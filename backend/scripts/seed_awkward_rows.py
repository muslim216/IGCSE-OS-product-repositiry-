"""Fill a database with awkward synthetic rows, and compare table row counts.

CI's `migrations` job runs every migration on an empty database, where a
migration never meets a real row. This script is the realistic-data half: after
`seed.demo` has filled a database at the base branch's schema, it adds rows of
the shapes that break migrations in practice — text at each column's declared
length, very long free text, empty strings, NULLs, names that differ only by
case or whitespace, Arabic and emoji — then the job applies the PR's migrations
on top.

Rows are generated by reflecting the live database, not from the models, so a
table added by a new migration is covered without editing this file. It imports
nothing from `app.models` for the same reason: the schema being filled is the
base branch's, and the models describe the PR's.

Everything is synthetic. Failed inserts (a CHECK or UNIQUE the generator cannot
know about) are rolled back to a savepoint and reported, never fatal; the run
fails if nothing at all was inserted, or if any table is still empty and not
named in EMPTY_OK.

Usage (from backend/, DATABASE_URL set as for the app):
  python -m scripts.seed_awkward_rows seed
  python -m scripts.seed_awkward_rows counts OUT.json
  python -m scripts.seed_awkward_rows compare BEFORE.json AFTER.json
"""

import argparse
import asyncio
import datetime as dt
import json
import os
import re
import sys
import tempfile
import uuid
from pathlib import Path
from typing import Any

from sqlalchemy import JSON, MetaData, insert, select, sql, types
from sqlalchemy.ext.asyncio import create_async_engine

from app.config import get_settings

# Alembic's bookkeeping table is not data.
SKIP_TABLES = {"alembic_version"}

# Tables allowed to end the seed with no rows, each with the reason. Anything else
# empty means the generator silently failed to cover a table, which is the exact
# hole this check exists to close, so it fails the run.
EMPTY_OK: dict[str, str] = {
    "narratives": "CHECK ck_narratives_exactly_one_target needs exactly one target column set; the generator cannot know that",
}

# A PR that must lose rows says so in a migration it adds, e.g.
#   # realistic-data: may-drop-rows <table>
#   # realistic-data: may-drop-table <table>
# Destructive migrations are High-risk and need the owner's sign-off.
MARKER = re.compile(r"#\s*realistic-data:\s*may-drop-(rows|table)\s+(\w+)")

# One generated row per variant, per table.
VARIANTS = ("max", "unicode", "empty", "nulls", "dupe_a", "dupe_b")

LONG_FREE_TEXT_CHARS = 20_000
ARABIC = "مرحبا بالعالم، هذا نص تجريبي"
EMOJI = "🧪📚✅🎓"


def awkward_string(length: int | None, variant: str, n: int) -> str:
    """A synthetic string for one cell.

    `length` is the column's declared limit, or None for unbounded text. The
    result never exceeds `length`. The counter `n` leads the value so rows stay
    distinct under a UNIQUE constraint, except in the dupe variants, whose whole
    point is values that look the same.
    """
    if variant == "empty":
        return ""
    if variant == "dupe_a":
        text = "Sample Name"
    elif variant == "dupe_b":
        text = "  sample name "
    elif variant == "unicode":
        text = f"{n}-{ARABIC} {EMOJI}"
    else:
        # "max" and "nulls": as long as the column allows.
        target = length if length is not None else LONG_FREE_TEXT_CHARS
        text = (f"{n}-" + "x" * target)[:target]
    if length is not None:
        text = text[:length]
    return text


def parse_markers(texts: list[str]) -> tuple[set[str], set[str]]:
    """(tables allowed to lose rows, tables allowed to vanish) from migration text."""
    found = [m.groups() for t in texts for m in MARKER.finditer(t)]
    return {n for k, n in found if k == "rows"}, {n for k, n in found if k == "table"}


def compare_counts(
    before: dict[str, int],
    after: dict[str, int],
    may_lose_rows: set[str] | frozenset[str] = frozenset(),
    may_drop: set[str] | frozenset[str] = frozenset(),
) -> tuple[list[str], list[str]]:
    """Return (report lines, failures).

    A row count cannot see an UPDATE that blanks or truncates values; it only
    catches rows deleted or tables dropped. An empty table that disappears is
    harmless; a populated one needs a marker (see MARKER).
    """
    lines = [f"{'table':<44}{'before':>9}{'after':>9}"]
    failures: list[str] = []
    for table in sorted(set(before) | set(after)):
        b, a = before.get(table), after.get(table)
        if a is None:
            flag = ""
            if b and table not in may_drop:
                flag = "  <-- POPULATED TABLE DROPPED"
                failures.append(f"{table}: dropped with {b} rows")
            lines.append(f"{table:<44}{b!s:>9}{'dropped':>9}{flag}")
            continue
        flag = ""
        if b is not None and a < b and table not in may_lose_rows:
            flag = "  <-- ROWS LOST"
            failures.append(f"{table}: {b} -> {a}")
        lines.append(f"{table:<44}{b if b is not None else 'new'!s:>9}{a:>9}{flag}")
    return lines, failures


def _simple_value(t: Any, variant: str, n: int) -> Any:
    """Values for text, numbers and booleans, or `...` for any other type."""
    if isinstance(t, types.Boolean):
        return n % 2 == 0
    if isinstance(t, (types.String, types.Text)):
        return awkward_string(getattr(t, "length", None), variant, n)
    if isinstance(t, types.Integer):
        return 1 + n % 7
    if isinstance(t, (types.Numeric, types.Float)):
        return 0.5
    return ...


def _other_value(t: Any, n: int) -> Any:
    """Values for dates, times, uuids, binary and JSON, or `...` if unhandled."""
    if isinstance(t, types.DateTime):
        now = dt.datetime.now(dt.timezone.utc)
        return now if t.timezone else now.replace(tzinfo=None)
    if isinstance(t, types.Date):
        return dt.date.today()
    if isinstance(t, types.Time):
        return dt.time(12, 0)
    if isinstance(t, types.Uuid) or type(t).__name__ == "UUID":
        return uuid.uuid4()
    if isinstance(t, types.LargeBinary):
        return b""
    if isinstance(t, JSON) or type(t).__name__ in {"JSONB", "JSON"}:
        return {"note": awkward_string(2000, "unicode", n), "empty": "", "none": None}
    return ...


def _value(col: Any, variant: str, n: int, parent_value: Any) -> Any:
    """A value for a reflected column, or the sentinel `...` to leave it out."""
    if parent_value is not None:
        return parent_value
    if variant == "nulls" and col.nullable:
        return None
    value = _simple_value(col.type, variant, n)
    return _other_value(col.type, n) if value is ... else value


async def _parent_value(conn: Any, col: Any, offset: int) -> Any:
    """A value of the referenced column from an existing parent row."""
    ref = next(iter(col.foreign_keys)).column
    row = (
        await conn.execute(
            select(ref).where(ref.is_not(None)).order_by(ref).limit(1).offset(offset)
        )
    ).first()
    if row is None:
        row = (await conn.execute(select(ref).where(ref.is_not(None)).limit(1))).first()
    return None if row is None else row[0]


async def _existing_value(conn: Any, col: Any, offset: int) -> Any:
    """A value already stored in this column, or None."""
    row = (
        await conn.execute(
            select(col).where(col.is_not(None)).distinct().order_by(col).limit(1).offset(offset)
        )
    ).first()
    if row is None and offset:
        return await _existing_value(conn, col, 0)
    return None if row is None else row[0]


def is_numbered_by_db(table: Any, col: Any) -> bool:
    """A lone integer primary key with no foreign key: the database numbers it.

    A composite-key link table's integer columns are the parent ids and must be
    given one (they are often PK and FK at once).
    """
    return (
        col.primary_key
        and isinstance(col.type, types.Integer)
        and not col.foreign_keys
        and len(table.primary_key.columns) == 1
    )


_SKIP = object()  # this row cannot be built
_OMIT = object()  # leave this column to the database


def _skip(notes: dict[str, set[str]], table: Any, why: str) -> object:
    notes.setdefault(table.name, set()).add(why)
    return _SKIP


def _is_enum_like(col: Any, variant: str) -> bool:
    return (
        isinstance(col.type, types.String)
        and not isinstance(col.type, types.Text)
        and 0 < (col.type.length or 0) <= 32
        and not (variant == "nulls" and col.nullable)
    )


async def _column_value(
    conn: Any, table: Any, col: Any, variant: str, n: int, notes: dict[str, set[str]]
) -> Any:
    """The value for one column, `_OMIT` to leave it out or `_SKIP` to drop the row."""
    if is_numbered_by_db(table, col):
        return _OMIT
    parent = None
    if col.foreign_keys:
        parent = await _parent_value(conn, col, n)
        if parent is None:
            if col.nullable:
                return None
            return _skip(notes, table, f"no parent row for {col.name}")
    if parent is None and _is_enum_like(col, variant):
        # Short strings are enum-like (DB-5): reuse a real value so a migration
        # adding a CHECK is not failed by rows production cannot hold.
        parent = await _existing_value(conn, col, n)
    value = _value(col, variant, n, parent)
    if value is ...:
        if not col.nullable and col.server_default is None:
            return _skip(notes, table, f"unhandled required column type {col.name}: {col.type!r}")
        return _OMIT
    return value


async def _row_values(
    conn: Any, table: Any, variant: str, n: int, notes: dict[str, set[str]]
) -> dict[str, Any] | None:
    values: dict[str, Any] = {}
    for col in table.columns:
        value = await _column_value(conn, table, col, variant, n, notes)
        if value is _SKIP:
            return None
        if value is not _OMIT:
            values[col.name] = value
    return values


async def _insert_row(conn: Any, table: Any, values: dict[str, Any]) -> str | None:
    """Insert in a savepoint; return why the database refused, or None."""
    try:
        async with conn.begin_nested():
            await conn.execute(insert(table).values(**values))
    except Exception as exc:  # noqa: BLE001 - anything the DB refuses is just a skipped row
        return f"{type(exc).__name__}: {str(exc).splitlines()[0][:100]}"
    return None


async def seed(
    conn: Any, metadata: MetaData, notes: dict[str, set[str]] | None = None
) -> tuple[int, int, dict[str, int]]:
    """Insert awkward rows. `notes` collects, per table, why rows were skipped."""
    notes = notes if notes is not None else {}
    failed_total = 0
    per_table: dict[str, int] = {}
    # sorted_tables puts parents before children, so FK targets exist by the
    # time a child is filled.
    for table in metadata.sorted_tables:
        if table.name in SKIP_TABLES:
            continue
        done = 0
        for n, variant in enumerate(VARIANTS, start=1):
            values = await _row_values(conn, table, variant, n, notes)
            if values is None:
                continue
            refused = await _insert_row(conn, table, values)
            if refused is None:
                done += 1
            else:
                failed_total += 1
                notes.setdefault(table.name, set()).add(f"{variant} refused: {refused}")
        per_table[table.name] = done
    return sum(per_table.values()), failed_total, per_table


async def _reflect(conn: Any) -> MetaData:
    metadata = MetaData()
    await conn.run_sync(metadata.reflect)
    return metadata


async def run_seed() -> int:
    engine = create_async_engine(get_settings().database_url)
    notes: dict[str, set[str]] = {}
    try:
        async with engine.begin() as conn:
            metadata = await _reflect(conn)
            inserted, failed, per_table = await seed(conn, metadata, notes)
            totals = {
                t.name: (await conn.execute(select(sql.func.count()).select_from(t))).scalar_one()
                for t in metadata.sorted_tables
                if t.name not in SKIP_TABLES
            }
    finally:
        await engine.dispose()
    for name in sorted(notes):
        for note in sorted(notes[name]):
            print(f"  {name}: {note}")
    covered = sum(1 for v in per_table.values() if v)
    print(
        f"Awkward rows: {inserted} inserted, {failed} refused, {covered}/{len(per_table)} tables covered."
    )
    if inserted == 0:
        print("::error::no awkward rows could be inserted; the check would prove nothing")
        return 1
    empty = sorted(t for t, c in totals.items() if c == 0 and t not in EMPTY_OK)
    if empty:
        print(f"::error::tables still empty after seeding (add rows or list in EMPTY_OK): {empty}")
        return 1
    return 0


async def collect_counts() -> dict[str, int]:
    engine = create_async_engine(get_settings().database_url)
    try:
        async with engine.connect() as conn:
            metadata = await _reflect(conn)
            counts: dict[str, int] = {}
            for table in metadata.sorted_tables:
                if table.name in SKIP_TABLES:
                    continue
                counts[table.name] = (
                    await conn.execute(select(sql.func.count()).select_from(table))
                ).scalar_one()
    finally:
        await engine.dispose()
    return counts


def checked_path(raw: str, root: Path | None = None) -> Path:
    """Resolve a CLI path and refuse anything outside `root`.

    The default root is the runner's temp directory, where CI keeps the count
    files; this stops a stray argument reading or overwriting other files.
    """
    base = (root or Path(os.environ.get("RUNNER_TEMP") or tempfile.gettempdir())).resolve()
    resolved = Path(raw).resolve()
    if not resolved.is_relative_to(base):
        raise SystemExit(f"::error::refusing path outside {base}: {raw}")
    return resolved


def run_counts(out: str) -> int:
    target = checked_path(out)
    counts = asyncio.run(collect_counts())
    with open(target, "w") as fh:
        json.dump(counts, fh)
    print(f"Counted {len(counts)} tables, {sum(counts.values())} rows -> {out}")
    return 0


def run_compare(before_path: str, after_path: str, migrations: list[str]) -> int:
    with open(checked_path(before_path)) as fh:
        before = json.load(fh)
    with open(checked_path(after_path)) as fh:
        after = json.load(fh)
    versions = Path.cwd() / "alembic" / "versions"
    texts = []
    for path in migrations:
        with open(checked_path(path, versions)) as fh:
            texts.append(fh.read())
    lines, failures = compare_counts(before, after, *parse_markers(texts))
    print("\n".join(lines))
    if failures:
        print(
            f"::error::row counts fell after the migrations: {', '.join(failures)}. If the loss "
            "is intended, add '# realistic-data: may-drop-rows <table>' (or may-drop-table) to a "
            "migration this PR adds; destructive migrations need the owner's sign-off."
        )
        return 1
    print("No table lost rows.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("seed")
    sub.add_parser("counts").add_argument("out")
    cmp_ = sub.add_parser("compare")
    cmp_.add_argument("before")
    cmp_.add_argument("after")
    cmp_.add_argument("migrations", nargs="*", help="migration files this PR adds")
    args = parser.parse_args(argv)
    if args.cmd == "seed":
        return asyncio.run(run_seed())
    if args.cmd == "counts":
        return run_counts(args.out)
    return run_compare(args.before, args.after, args.migrations)


if __name__ == "__main__":
    sys.exit(main())
