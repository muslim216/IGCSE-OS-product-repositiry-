"""The one reader of `requirements*.lock`, shared by the drift test and CI's checks.

Three lock files live in backend/, all written by `uv pip compile` with hashes:

  requirements.lock        runtime set; what the production image installs
  requirements-build.lock  the build backend (setuptools) the image and CI need
                           because the app is installed with --no-build-isolation
  requirements-dev.lock    runtime set + pytest, ruff, mypy, uv; what CI installs.
                           Compiled with `-c requirements.lock`, so a runtime
                           package cannot sit at two versions across the files.

Parsing is line by line, with no regular expression over the whole file: a lock
is a few thousand lines of `name==version ; marker \\` followed by indented
`--hash=` lines and `#` comments, and a pattern that backtracks on a hostile
line (it has been timed at 15 s) has no business in a check that runs on every
pull request.
"""

import pathlib
from dataclasses import dataclass, field

from packaging.requirements import InvalidRequirement, Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

BACKEND = pathlib.Path(__file__).resolve().parent.parent
RUNTIME_LOCK = BACKEND / "requirements.lock"
BUILD_LOCK = BACKEND / "requirements-build.lock"
DEV_LOCK = BACKEND / "requirements-dev.lock"
# Order matters when regenerating: the dev lock is compiled against the runtime one.
ALL_LOCKS = (RUNTIME_LOCK, BUILD_LOCK, DEV_LOCK)


@dataclass
class Pin:
    name: str  # canonical (lowercase, runs of -_. collapsed to -)
    version: Version
    marker: str | None = None
    hashes: list[str] = field(default_factory=list)

    def applies_here(self) -> bool:
        """False for a pin whose environment marker does not hold on this interpreter."""
        if self.marker is None:
            return True
        return Requirement(f"x; {self.marker}").marker.evaluate()  # type: ignore[union-attr]


def _parse_pin(line: str, path: pathlib.Path) -> Pin:
    try:
        req = Requirement(line)
    except InvalidRequirement as exc:
        raise ValueError(f"{path.name}: cannot read line {line[:80]!r}: {exc}") from exc
    specs = list(req.specifier)
    if len(specs) != 1 or specs[0].operator != "==":
        raise ValueError(f"{path.name}: not an exact pin: {line[:80]!r}")
    return Pin(
        name=canonicalize_name(req.name),
        version=Version(specs[0].version),
        marker=str(req.marker) if req.marker is not None else None,
    )


def parse_lock(path: pathlib.Path) -> list[Pin]:
    pins: list[Pin] = []
    for raw in path.read_text().splitlines():
        line = raw.strip().removesuffix("\\").strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("--hash="):
            if not pins:
                raise ValueError(f"{path.name}: hash line before any pin: {line[:60]}")
            pins[-1].hashes.append(line.removeprefix("--hash="))
        else:
            pins.append(_parse_pin(line, path))
    return pins


def versions(path: pathlib.Path) -> dict[str, Version]:
    return {p.name: p.version for p in parse_lock(path)}


def header_command(path: pathlib.Path) -> str:
    """The `uv pip compile ...` command a lock's header says produced it."""
    lines = path.read_text().splitlines()
    for i, line in enumerate(lines[:6]):
        if "via the following command" in line and i + 1 < len(lines):
            return lines[i + 1].lstrip("# ").strip()
    raise ValueError(f"{path.name}: no 'autogenerated by uv' command in the header")


def regenerate_hint() -> str:
    """Exact shell for rebuilding every lock from backend/, taken from the headers.

    Deleting first matters: uv treats an existing output file as version
    preferences, but CI compares against a from-scratch resolve.
    """
    try:
        commands = [header_command(p) for p in ALL_LOCKS]
    except (OSError, ValueError):
        commands = ["<see the 'autogenerated' header line of each requirements*.lock>"]
    names = " ".join(p.name for p in ALL_LOCKS)
    return "To fix, from backend/:\n  rm " + names + "\n  " + "\n  ".join(commands)
